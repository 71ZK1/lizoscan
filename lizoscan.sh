#!/usr/bin/env bash
#
# lizoscan.sh
# Takes a pre-built list of URLs (from YOUR OWN recon/subdomain tool) and
# runs it through parameter classification + a wide spread of vulnerability
# scanners (nuclei across many template categories, dalfox, sqlmap,
# crlfuzz, Corsy, ffuf, nikto). No subdomain enumeration happens here —
# bring your own URL list.
#
# Everything is written as .txt under: scan results/<name>/
#
# USAGE:
#   ./lizoscan.sh -l urls.txt              (urls.txt = one URL per line)
#   ./lizoscan.sh -l urls.txt -n myscan    (custom output folder name)
#
# For use ONLY against targets you own or are explicitly authorized to test.
# Running this against systems without permission is illegal.

set -uo pipefail
export PATH="$PATH:$HOME/go/bin"

GREEN="\e[32m"; CYAN="\e[36m"; YELLOW="\e[33m"; RED="\e[31m"; RESET="\e[0m"
log()   { echo -e "${GREEN}[+]${RESET} $*"; }
info()  { echo -e "${CYAN}[*]${RESET} $*"; }
warn()  { echo -e "${YELLOW}[!]${RESET} $*"; }
err()   { echo -e "${RED}[-]${RESET} $*"; }

need_cmd() { command -v "$1" >/dev/null 2>&1; }

usage() {
    echo "Usage: $0 -l <urls.txt> [-n <scan-name>]"
    echo
    echo "  -l   Path to a text file containing URLs to scan (one per line)."
    echo "       This file is expected to already exist — e.g. generated by"
    echo "       your own recon/subdomain tool."
    echo "  -n   Optional name for the output folder under 'scan results/'."
    echo "       Defaults to the input file's base name."
    exit 1
}

INPUT_FILE=""
SCAN_NAME=""
while getopts "l:n:h" opt; do
    case "$opt" in
        l) INPUT_FILE="$OPTARG" ;;
        n) SCAN_NAME="$OPTARG" ;;
        h) usage ;;
        *) usage ;;
    esac
done

[ -z "$INPUT_FILE" ] && usage
[ -f "$INPUT_FILE" ] || { err "Input file not found: $INPUT_FILE"; exit 1; }
[ -s "$INPUT_FILE" ] || { err "Input file is empty: $INPUT_FILE"; exit 1; }

if [ -z "$SCAN_NAME" ]; then
    SCAN_NAME="$(basename "$INPUT_FILE")"
    SCAN_NAME="${SCAN_NAME%.*}"
fi

BASE_DIR="scan results"
OUT="$BASE_DIR/$SCAN_NAME"
URLS="$OUT/urls"
PARAMS="$OUT/params"
VULN="$OUT/vuln"
NUCLEI_DIR="$VULN/nuclei"
mkdir -p "$URLS" "$PARAMS" "$VULN" "$NUCLEI_DIR"

echo
log "=============================================="
log " LIZOSCAN — Input: $INPUT_FILE"
log " Output:  $OUT/"
log "=============================================="

# ---------------------------------------------------------------------
# 1. Load the provided URL list (deduped, as-is — no discovery/enum)
# ---------------------------------------------------------------------
sort -u "$INPUT_FILE" > "$URLS/input_urls.txt"
log "URLs loaded: $(wc -l < "$URLS/input_urls.txt")"

# ---------------------------------------------------------------------
# 2. Validate which URLs are actually alive (httpx), if available
# ---------------------------------------------------------------------
if need_cmd httpx; then
    info "Validating which URLs are alive..."
    httpx -l "$URLS/input_urls.txt" -silent -o "$URLS/valid_urls.txt" \
        -status-code -title -tech-detect 2>/dev/null
    awk '{print $1}' "$URLS/valid_urls.txt" | sort -u > "$URLS/alive_urls.txt"
    log "Alive/valid URLs: $(wc -l < "$URLS/alive_urls.txt")"
else
    warn "httpx not found — scanning the full input list as-is."
    cp "$URLS/input_urls.txt" "$URLS/alive_urls.txt"
    cp "$URLS/input_urls.txt" "$URLS/valid_urls.txt"
fi

# ---------------------------------------------------------------------
# 3. Parameter discovery + classification (gf)
# ---------------------------------------------------------------------
grep '=' "$URLS/alive_urls.txt" | sort -u > "$PARAMS/urls_with_params.txt" 2>/dev/null
log "URLs with parameters: $(wc -l < "$PARAMS/urls_with_params.txt" 2>/dev/null || echo 0)"

if need_cmd gf && [ -s "$PARAMS/urls_with_params.txt" ]; then
    info "Classifying parameters with gf patterns..."
    for pattern in xss sqli ssrf lfi redirect rce idor ssti; do
        gf "$pattern" < "$PARAMS/urls_with_params.txt" > "$PARAMS/gf_${pattern}.txt" 2>/dev/null
        [ -s "$PARAMS/gf_${pattern}.txt" ] && \
            log "  -> $pattern candidates: $(wc -l < "$PARAMS/gf_${pattern}.txt")"
    done
fi

# ---------------------------------------------------------------------
# 4. nuclei — run across many template categories separately, plus a
#    combined full run, so results are both categorized and complete.
# ---------------------------------------------------------------------
if need_cmd nuclei && [ -s "$URLS/alive_urls.txt" ]; then
    declare -A NUCLEI_TAGS=(
        [cves]="cve"
        [exposures]="exposure"
        [misconfiguration]="misconfig"
        [vulnerabilities]="vuln"
        [default_logins]="default-login"
        [takeovers]="takeover"
        [technologies]="tech"
    )

    for label in "${!NUCLEI_TAGS[@]}"; do
        tag="${NUCLEI_TAGS[$label]}"
        info "nuclei: scanning '$tag' templates..."
        nuclei -l "$URLS/alive_urls.txt" -silent -tags "$tag" \
            -o "$NUCLEI_DIR/${label}_results.txt" 2>/dev/null
        count=$(wc -l < "$NUCLEI_DIR/${label}_results.txt" 2>/dev/null || echo 0)
        log "  -> $label findings: $count"
    done

    info "nuclei: running the full template set (all categories)..."
    nuclei -l "$URLS/alive_urls.txt" -silent \
        -o "$NUCLEI_DIR/full_results.txt" 2>/dev/null
    log "nuclei full-run findings: $(wc -l < "$NUCLEI_DIR/full_results.txt" 2>/dev/null || echo 0)"

    cat "$NUCLEI_DIR"/*_results.txt 2>/dev/null | sort -u > "$VULN/nuclei_results.txt"
    log "nuclei combined unique findings: $(wc -l < "$VULN/nuclei_results.txt" 2>/dev/null || echo 0)"
else
    warn "nuclei not found or no alive URLs — skipping nuclei stage."
fi

# ---------------------------------------------------------------------
# 5. dalfox — XSS scan on candidate parameters
# ---------------------------------------------------------------------
if need_cmd dalfox && [ -s "$PARAMS/gf_xss.txt" ]; then
    info "Running dalfox on candidate XSS parameters..."
    dalfox file "$PARAMS/gf_xss.txt" --silence \
        -o "$VULN/dalfox_results.txt" 2>/dev/null
    log "dalfox findings written to $VULN/dalfox_results.txt"
fi

# ---------------------------------------------------------------------
# 6. sqlmap — confirm SQLi on candidate parameters
# ---------------------------------------------------------------------
if need_cmd sqlmap && [ -s "$PARAMS/gf_sqli.txt" ]; then
    info "Running sqlmap against candidate SQLi parameters..."
    : > "$VULN/sqlmap_results.txt"
    while IFS= read -r url; do
        echo "### $url" >> "$VULN/sqlmap_results.txt"
        sqlmap -u "$url" --batch --random-agent --level=1 --risk=1 \
            --disable-coloring 2>/dev/null \
            | grep -Ei "is vulnerable|parameter.*injectable|back-end DBMS" \
            >> "$VULN/sqlmap_results.txt"
        echo >> "$VULN/sqlmap_results.txt"
    done < "$PARAMS/gf_sqli.txt"
    log "sqlmap results written to $VULN/sqlmap_results.txt"
fi

# ---------------------------------------------------------------------
# 7. crlfuzz — CRLF injection
# ---------------------------------------------------------------------
if need_cmd crlfuzz && [ -s "$URLS/alive_urls.txt" ]; then
    info "Testing for CRLF injection..."
    crlfuzz -l "$URLS/alive_urls.txt" -s -o "$VULN/crlf_results.txt" 2>/dev/null
    log "crlfuzz findings: $(wc -l < "$VULN/crlf_results.txt" 2>/dev/null || echo 0)"
fi

# ---------------------------------------------------------------------
# 8. Corsy — CORS misconfiguration
# ---------------------------------------------------------------------
if [ -x "$HOME/tools/Corsy/corsy.py" ] && [ -s "$URLS/alive_urls.txt" ]; then
    info "Checking for CORS misconfigurations..."
    python3 "$HOME/tools/Corsy/corsy.py" -i "$URLS/alive_urls.txt" \
        -o "$VULN/cors_results.txt" >/dev/null 2>&1
    log "CORS results written to $VULN/cors_results.txt"
fi

# ---------------------------------------------------------------------
# 9. ffuf — hidden content/directory fuzzing
# ---------------------------------------------------------------------
if need_cmd ffuf && [ -s "$URLS/alive_urls.txt" ]; then
    info "Fuzzing for hidden directories/files..."
    : > "$VULN/ffuf_results.txt"
    WORDLIST="/usr/share/wordlists/dirb/common.txt"
    [ -f "$WORDLIST" ] || WORDLIST="$HOME/tools/wordlists/common.txt"
    if [ -f "$WORDLIST" ]; then
        while IFS= read -r host; do
            echo "### $host" >> "$VULN/ffuf_results.txt"
            ffuf -u "${host}/FUZZ" -w "$WORDLIST" -mc 200,204,301,302,307,401,403 \
                -s 2>/dev/null >> "$VULN/ffuf_results.txt"
        done < "$URLS/alive_urls.txt"
        log "ffuf results written to $VULN/ffuf_results.txt"
    else
        warn "No wordlist found for ffuf — skipping content discovery."
    fi
fi

# ---------------------------------------------------------------------
# 10. nikto — general web vulnerability scan
# ---------------------------------------------------------------------
if need_cmd nikto && [ -s "$URLS/alive_urls.txt" ]; then
    info "Running nikto on alive URLs..."
    : > "$VULN/nikto_results.txt"
    while IFS= read -r host; do
        echo "### $host" >> "$VULN/nikto_results.txt"
        nikto -h "$host" -ask no 2>/dev/null >> "$VULN/nikto_results.txt"
        echo >> "$VULN/nikto_results.txt"
    done < "$URLS/alive_urls.txt"
    log "nikto results written to $VULN/nikto_results.txt"
fi

# ---------------------------------------------------------------------
# 11. Consolidated report
# ---------------------------------------------------------------------
REPORT="$OUT/report.txt"
{
    echo "==================================================="
    echo " LIZOSCAN REPORT — $SCAN_NAME"
    echo " Input file: $INPUT_FILE"
    echo " Generated: $(date -u '+%Y-%m-%d %H:%M:%S UTC')"
    echo "==================================================="
    echo
    echo "--- URLs loaded from input ---"
    wc -l < "$URLS/input_urls.txt" 2>/dev/null
    echo
    echo "--- Alive/valid URLs ---"
    wc -l < "$URLS/alive_urls.txt" 2>/dev/null
    echo
    echo "--- URLs with parameters ---"
    wc -l < "$PARAMS/urls_with_params.txt" 2>/dev/null
    echo
    echo "--- nuclei: combined unique findings (all categories) ---"
    if [ -s "$VULN/nuclei_results.txt" ]; then
        cat "$VULN/nuclei_results.txt"
    else
        echo "(none found / nuclei not run)"
    fi
    echo
    echo "--- dalfox XSS findings ---"
    if [ -s "$VULN/dalfox_results.txt" ]; then
        cat "$VULN/dalfox_results.txt"
    else
        echo "(none found / dalfox not run)"
    fi
    echo
    echo "--- sqlmap confirmed SQLi ---"
    if [ -s "$VULN/sqlmap_results.txt" ]; then
        cat "$VULN/sqlmap_results.txt"
    else
        echo "(none found / sqlmap not run)"
    fi
    echo
    echo "--- CRLF injection (crlfuzz) ---"
    if [ -s "$VULN/crlf_results.txt" ]; then
        cat "$VULN/crlf_results.txt"
    else
        echo "(none found / crlfuzz not run)"
    fi
    echo
    echo "--- CORS misconfigurations (Corsy) ---"
    if [ -s "$VULN/cors_results.txt" ]; then
        cat "$VULN/cors_results.txt"
    else
        echo "(none found / Corsy not run)"
    fi
    echo
    echo "--- Hidden content (ffuf) ---"
    if [ -s "$VULN/ffuf_results.txt" ]; then
        cat "$VULN/ffuf_results.txt"
    else
        echo "(none found / ffuf not run)"
    fi
    echo
    echo "--- nikto findings ---"
    if [ -s "$VULN/nikto_results.txt" ]; then
        cat "$VULN/nikto_results.txt"
    else
        echo "(none found / nikto not run)"
    fi
    echo
    echo "==================================================="
    echo " Per-category nuclei output lives under: $NUCLEI_DIR/"
    echo " All raw tool output lives under: $OUT/"
    echo "==================================================="
} > "$REPORT"

log "Report written: $REPORT"
echo
log "Done. Results are under: \"$OUT/\""
